#!/usr/bin/env node
// The Iris aperture mark (I11, spec §7): design/iris/mark.json + tokens.json →
// the mark and its app-icon / launch SVGs. No dependencies; PNGs are rendered
// from these by apple/scripts/render-mark.sh.
//   node scripts/iris-mark.js          write every output
//   node scripts/iris-mark.js --check  exit 1 if a committed output is stale
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const SOURCES = { mark: 'design/iris/mark.json', tokens: 'design/iris/tokens.json' };
const OUTPUTS = {
  mark: 'design/iris/mark.svg',
  light: 'design/iris/icon/light.svg',
  dark: 'design/iris/icon/dark.svg',
  tinted: 'design/iris/icon/tinted.svg',
  launchLight: 'design/iris/icon/launch-light.svg',
  launchDark: 'design/iris/icon/launch-dark.svg',
};
const SIZE = 1024;
const STEPS = 16; // arc segments per blade

function hex(value, where) {
  if (typeof value !== 'string' || !/^#[0-9A-Fa-f]{6}$/.test(value)) throw new Error(`${where}: "${value}" is not #RRGGBB`);
  return value.toUpperCase();
}

/** One blade's outline: the outer arc, closed through two twisted inner vertices. */
function blade(i, m) {
  const c = SIZE / 2;
  const pt = (r, deg) => {
    const a = ((deg - 90) * Math.PI) / 180;
    return [c + r * Math.cos(a), c + r * Math.sin(a)];
  };
  const t0 = (i * 360) / m.blades;
  const t1 = t0 + 360 / m.blades;
  const arc = Array.from({ length: STEPS + 1 }, (_, k) => pt(m.outerRadius, t0 + ((t1 - t0) * k) / STEPS));
  const points = [...arc, pt(m.innerRadius, t1 + m.twist), pt(m.innerRadius, t0 + m.twist)];
  return 'M' + points.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join(' L') + ' Z';
}

function validate(mark, tokens) {
  for (const k of ['blades', 'outerRadius', 'innerRadius', 'twist', 'gap'])
    if (typeof mark[k] !== 'number') throw new Error(`mark.json: "${k}" must be a number`);
  for (const k of ['order', 'tinted'])
    if (!Array.isArray(mark[k]) || mark[k].length !== mark.blades) throw new Error(`mark.json: "${k}" needs ${mark.blades} entries`);
  const colour = (name, mode, i) => {
    const t = tokens.color?.[name];
    if (!t) throw new Error(`mark.json: order[${i}] names no colour token "${name}"`);
    return hex(t[mode], `color.${name}.${mode}`);
  };
  const fills = { light: [], dark: [] };
  mark.order.forEach((entry, i) => {
    for (const mode of ['light', 'dark']) fills[mode].push(colour(typeof entry === 'string' ? entry : entry[mode], mode, i));
  });
  fills.tinted = mark.tinted.map((level, i) => {
    if (typeof level !== 'number' || level < 0 || level > 1) throw new Error(`mark.json: tinted[${i}] must be 0…1`);
    const g = Math.round(level * 255).toString(16).padStart(2, '0').toUpperCase();
    return `#${g}${g}${g}`;
  });
  return fills;
}

function svg(m, header, fills, { background, gap }) {
  const lines = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}">`,
    `<!-- GENERATED by scripts/iris-mark.js — do not edit. Sources: ${header} -->`,
  ];
  if (background) lines.push(`<rect width="${SIZE}" height="${SIZE}" fill="${background}"/>`);
  fills.forEach((fill, i) =>
    lines.push(`<path d="${blade(i, m)}" fill="${fill}" stroke="${gap}" stroke-width="${m.gap}" stroke-linejoin="round"/>`));
  lines.push('</svg>', '');
  return lines.join('\n');
}

function generate(markRaw, tokensRaw) {
  const parse = (raw, name) => {
    try {
      return JSON.parse(raw);
    } catch (e) {
      throw new Error(`${name}: invalid JSON — ${e.message}`);
    }
  };
  const mark = parse(markRaw, 'mark.json');
  const fills = validate(mark, parse(tokensRaw, 'tokens.json'));
  const hash = (s) => crypto.createHash('sha256').update(s).digest('hex');
  const header = `mark.json ${hash(markRaw)}, tokens.json ${hash(tokensRaw)}`;
  const W = '#FFFFFF';
  const B = '#000000';
  return {
    // The mark on its own: light colours, gaps cut in white (docs, landing page).
    mark: svg(mark, header, fills.light, { gap: W }),
    light: svg(mark, header, fills.light, { background: W, gap: W }),
    dark: svg(mark, header, fills.dark, { background: B, gap: B }),
    tinted: svg(mark, header, fills.tinted, { background: B, gap: B }),
    // Launch marks sit on LaunchBackground (white / black), so gaps match it.
    launchLight: svg(mark, header, fills.light, { gap: W }),
    launchDark: svg(mark, header, fills.dark, { gap: B }),
  };
}

function main(argv, root = ROOT) {
  let out;
  try {
    out = generate(fs.readFileSync(path.join(root, SOURCES.mark), 'utf8'), fs.readFileSync(path.join(root, SOURCES.tokens), 'utf8'));
  } catch (e) {
    console.error(e.message);
    return 1;
  }
  if (argv.includes('--check')) {
    const stale = Object.entries(OUTPUTS).filter(([key, rel]) => {
      const file = path.join(root, rel);
      return !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out[key];
    }).map(([, rel]) => rel);
    if (stale.length) {
      console.error(`Stale — run \`npm run mark\`:\n  ${stale.join('\n  ')}`);
      return 1;
    }
    console.log('Iris mark up to date');
    return 0;
  }
  for (const [key, rel] of Object.entries(OUTPUTS)) {
    const file = path.join(root, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, out[key]);
    console.log(`wrote ${rel}`);
  }
  return 0;
}

module.exports = { generate, main, OUTPUTS, SOURCES };
if (require.main === module) process.exit(main(process.argv.slice(2)));
